-- ============================================================
-- SO订单管理 建表脚本
-- ============================================================

-- 1. SO订单主表
CREATE TABLE IF NOT EXISTS `export_vehicle_cbu_so` (
    `id`                          VARCHAR(64)      NOT NULL                          COMMENT '主键',
    `so_no`                       VARCHAR(30)      NOT NULL                          COMMENT 'SO单号，格式 SO + yyyyMMddHHmm + 5位流水',
    `po_id`                       VARCHAR(36)      NOT NULL                          COMMENT '关联PO单ID',
    `po_no`                       VARCHAR(30)      NOT NULL                          COMMENT 'PO单号',
    `po_detail_id`                VARCHAR(36)      DEFAULT NULL                      COMMENT '关联PO明细ID',
    `po_detail_no`                VARCHAR(30)      DEFAULT NULL                      COMMENT 'PO明细编号',
    `line_no`                     INT              DEFAULT NULL                      COMMENT '行号',
    `sales_company_code`          VARCHAR(30)      DEFAULT NULL                      COMMENT '销售公司编码',
    `customer_code`               VARCHAR(50)      NOT NULL                          COMMENT '客户编码',
    `customer_name`               VARCHAR(100)     DEFAULT NULL                      COMMENT '客户名称',
    `external_customer_code`      VARCHAR(50)      DEFAULT NULL                      COMMENT '外部客户编码',
    `order_type`                  TINYINT          DEFAULT NULL                      COMMENT '订单类型 字典: export_vehicle_cbu_po_order_type',
    `plan_version`                VARCHAR(50)      DEFAULT NULL                      COMMENT '计划版本号',
    `expected_offline_date`       DATE             DEFAULT NULL                      COMMENT '期望下线日期',
    `vin_year`                    VARCHAR(10)      DEFAULT NULL                      COMMENT 'VIN码年份',
    `production_remark`           VARCHAR(1000)    DEFAULT NULL                      COMMENT '生产备注',
    `vehicle_price`               DECIMAL(18,4)    DEFAULT NULL                      COMMENT '车辆价格，取自PO单',
    `frozen_amount`               DECIMAL(18,4)    DEFAULT NULL                      COMMENT '冻结金额，默认=车辆价格',
    `receivable_amount`           DECIMAL(18,4)    DEFAULT NULL                      COMMENT '应收金额，质检通过后由冻结金额转入',
    `order_status`                SMALLINT         NOT NULL DEFAULT '1001'           COMMENT '订单状态 字典: vehicle_cbu_so_order_status',
    `issue_time`                  DATETIME         DEFAULT NULL                      COMMENT '下发生产时间',
    `cancel_time`                 DATETIME         DEFAULT NULL                      COMMENT '作废时间',
    `qc_result`                   TINYINT          DEFAULT NULL                      COMMENT '当前质检结果 字典: vehicle_cbu_so_qc_result',
    `qc_result_time`              DATETIME         DEFAULT NULL                      COMMENT '当前质检结果反馈时间',
    `qc_remark`                   VARCHAR(500)     DEFAULT NULL                      COMMENT '当前质检说明',
    `last_qc_result`              TINYINT          DEFAULT NULL                      COMMENT '上次质检结果 字典: vehicle_cbu_so_qc_result',
    `last_qc_result_time`         DATETIME         DEFAULT NULL                      COMMENT '上次质检结果反馈时间',
    `last_qc_remark`              VARCHAR(500)     DEFAULT NULL                      COMMENT '上次质检说明',
    `receive_time`                DATETIME         DEFAULT NULL                      COMMENT '完成收款时间',
    `data_source`                 TINYINT          DEFAULT NULL                      COMMENT '数据来源 字典: export_vehicle_cbu_po_data_source',
    `remark`                      VARCHAR(500)     DEFAULT NULL                      COMMENT '备注',
    `creator`                     BIGINT           NOT NULL                          COMMENT '创建者ID',
    `creator_name`                VARCHAR(100)     NOT NULL                          COMMENT '创建人名称',
    `create_time`                 DATETIME         NOT NULL DEFAULT CURRENT_TIMESTAMP COMMENT '创建时间',
    `modifier`                    BIGINT           DEFAULT NULL                      COMMENT '修改者ID',
    `modifier_name`               VARCHAR(100)     DEFAULT NULL                      COMMENT '修改人名称',
    `update_time`                 DATETIME         DEFAULT NULL ON UPDATE CURRENT_TIMESTAMP COMMENT '修改时间',
    `delete_status`               BIGINT           NOT NULL DEFAULT '0'              COMMENT '删除状态(0=正常,1=已删除)',
    `status`                      SMALLINT UNSIGNED NOT NULL DEFAULT '1'             COMMENT '状态(1:启用,0:停用)',
    `status_desc`                 VARCHAR(256)     DEFAULT NULL                      COMMENT '状态变更描述',
    `owner_user_id`               BIGINT(20) UNSIGNED NOT NULL DEFAULT '0'             COMMENT '归属用户ID，当数据权限归属到用户时',
    `owner_org_id`                BIGINT(20) UNSIGNED NOT NULL DEFAULT '0'             COMMENT '归属门店ID（组织ID），当数据权限归属到本组织以及本下级',
    PRIMARY KEY (`id`),
    KEY `idx_so_no` (`so_no`),
    KEY `idx_po_no` (`po_no`),
    KEY `idx_customer_code` (`customer_code`),
    KEY `idx_order_status` (`order_status`),
    KEY `idx_create_time` (`create_time`)
) ENGINE = InnoDB DEFAULT CHARSET = utf8mb4 COLLATE = utf8mb4_general_ci COMMENT = 'CBU整车销售订单主表';

-- 2. SO车辆明细表
--    id 不再由 MyBatis-Plus 自动生成，1:1 复用主表 id；
--    so_id 重命名为 so_no（关联字段从主键 id 改为业务编号 so_no）。
CREATE TABLE IF NOT EXISTS `export_vehicle_cbu_so_detail` (
    `id`                          VARCHAR(64)      NOT NULL                          COMMENT '主键',
    `so_no`                       VARCHAR(30)      NOT NULL                          COMMENT '关联SO单号（冗余字段，业务关联走 m.id = d.id）',
    `internal_vehicle_no`         VARCHAR(50)      DEFAULT NULL                      COMMENT '内部车辆号，从APS获取',
    `production_identify_code`    VARCHAR(50)      DEFAULT NULL                      COMMENT '产销识别码，从APS获取',
    `vin`                         VARCHAR(50)      DEFAULT NULL                      COMMENT 'VIN号，从APS获取',
    `material_code`               VARCHAR(50)      DEFAULT NULL                      COMMENT '物料编码，取自PO单',
    `material_description`        VARCHAR(200)     DEFAULT NULL                      COMMENT '物料描述',
    `sales_market`                VARCHAR(50)      DEFAULT NULL                      COMMENT '销售市场',
    `model_year`                  VARCHAR(10)      DEFAULT NULL                      COMMENT '年款',
    `optional_package`            VARCHAR(100)     DEFAULT NULL                      COMMENT '选装包',
    `plan_offline_date`           DATE             DEFAULT NULL                      COMMENT '计划总装下线日期，从APS获取',
    `schedule_time`               DATETIME         DEFAULT NULL                      COMMENT '排产时间，从APS获取',
    `barcode_print_time`          DATETIME         DEFAULT NULL                      COMMENT '打印条码时间，从APS获取',
    `body_in_time`                DATETIME         DEFAULT NULL                      COMMENT '焊装上线时间，从APS获取',
    `paint_in_time`               DATETIME         DEFAULT NULL                      COMMENT '涂装上线时间，从APS获取',
    `assembly_in_time`            DATETIME         DEFAULT NULL                      COMMENT '总装上线时间，从APS获取',
    `assembly_out_time`           DATETIME         DEFAULT NULL                      COMMENT '总装下线时间，从APS获取',
    `sync_aps_result`             TINYINT          DEFAULT NULL                      COMMENT 'APS最新同步结果 字典: vehicle_cbu_so_sync_result',
    `sync_aps_time`               DATETIME         DEFAULT NULL                      COMMENT 'APS最新同步时间',
    `sync_aps_response_info`      VARCHAR(2000)    DEFAULT NULL                      COMMENT 'APS最新返回信息',
    `sync_sap_result`             TINYINT          DEFAULT NULL                      COMMENT 'SAP最新同步结果 字典: vehicle_cbu_so_sync_result',
    `sync_sap_time`               DATETIME         DEFAULT NULL                      COMMENT 'SAP最新同步时间',
    `sync_sap_response_info`      VARCHAR(2000)    DEFAULT NULL                      COMMENT 'SAP最新返回信息',
    `sync_customer_result`        TINYINT          DEFAULT NULL                      COMMENT '客户最新同步结果 字典: vehicle_cbu_so_sync_result',
    `sync_customer_time`          DATETIME         DEFAULT NULL                      COMMENT '客户最新同步时间',
    `sync_customer_response_info` VARCHAR(2000)    DEFAULT NULL                      COMMENT '客户最新返回信息',
    `remark`                      VARCHAR(500)     DEFAULT NULL                      COMMENT '备注',
    `creator`                     BIGINT           NOT NULL                          COMMENT '创建者ID',
    `creator_name`                VARCHAR(100)     NOT NULL                          COMMENT '创建人名称',
    `create_time`                 DATETIME         NOT NULL DEFAULT CURRENT_TIMESTAMP COMMENT '创建时间',
    `modifier`                    BIGINT           DEFAULT NULL                      COMMENT '修改者ID',
    `modifier_name`               VARCHAR(100)     DEFAULT NULL                      COMMENT '修改人名称',
    `update_time`                 DATETIME         DEFAULT NULL ON UPDATE CURRENT_TIMESTAMP COMMENT '修改时间',
    `delete_status`               BIGINT           NOT NULL DEFAULT '0'              COMMENT '删除状态(0=正常,1=已删除)',
    `status`                      SMALLINT UNSIGNED NOT NULL DEFAULT '1'             COMMENT '状态(1:启用,0:停用)',
    `status_desc`                 VARCHAR(256)     DEFAULT NULL                      COMMENT '状态变更描述',
    `owner_user_id`               BIGINT(20) UNSIGNED NOT NULL DEFAULT '0'             COMMENT '归属用户ID，当数据权限归属到用户时',
    `owner_org_id`                BIGINT(20) UNSIGNED NOT NULL DEFAULT '0'             COMMENT '归属门店ID（组织ID），当数据权限归属到本组织以及本下级',
    PRIMARY KEY (`id`),
    KEY `idx_so_no` (`so_no`),
    KEY `idx_vin` (`vin`),
    KEY `idx_production_identify_code` (`production_identify_code`),
    KEY `idx_internal_vehicle_no` (`internal_vehicle_no`),
    KEY `idx_material_code` (`material_code`)
) ENGINE = InnoDB DEFAULT CHARSET = utf8mb4 COLLATE = utf8mb4_general_ci COMMENT = 'SO车辆明细表（与主表 1:1）';

-- 3. SO接口同步记录表
--    so_id 字段保持不变，继续存主表 id 字符串。
CREATE TABLE IF NOT EXISTS `export_vehicle_cbu_so_interface_sync` (
    `id`             VARCHAR(64)  NOT NULL                          COMMENT '主键',
    `so_id`          VARCHAR(36)  NOT NULL                          COMMENT '关联SO主表ID（实际存主表 id 字符串）',
    `interface_type` TINYINT      NOT NULL                          COMMENT '接口类型 字典: vehicle_cbu_so_interface_type',
    `interface_desc` VARCHAR(255) DEFAULT NULL                      COMMENT '接口描述',
    `call_time`      DATETIME     NOT NULL                          COMMENT '调用时间',
    `request_info`   VARCHAR(2000) DEFAULT NULL                     COMMENT '请求报文',
    `result_status`  TINYINT      NOT NULL DEFAULT '0'              COMMENT '返回结果 字典: vehicle_cbu_so_sync_result',
    `response_info`  VARCHAR(2000) DEFAULT NULL                     COMMENT '返回报文',
    `remark`         VARCHAR(500) DEFAULT NULL                      COMMENT '备注',
    `creator`        BIGINT       NOT NULL                          COMMENT '创建者ID',
    `creator_name`   VARCHAR(100) NOT NULL                          COMMENT '创建人名称',
    `create_time`    DATETIME     NOT NULL DEFAULT CURRENT_TIMESTAMP COMMENT '创建时间',
    `modifier`       BIGINT       DEFAULT NULL                      COMMENT '修改者ID',
    `modifier_name`  VARCHAR(100) DEFAULT NULL                      COMMENT '修改人名称',
    `update_time`    DATETIME     DEFAULT NULL ON UPDATE CURRENT_TIMESTAMP COMMENT '修改时间',
    `delete_status`  BIGINT       NOT NULL DEFAULT '0'              COMMENT '删除状态(0=正常,1=已删除)',
    `status`         SMALLINT UNSIGNED NOT NULL DEFAULT '1'        COMMENT '状态(1:启用,0:停用)',
    `status_desc`    VARCHAR(256) DEFAULT NULL                      COMMENT '状态变更描述',
    `owner_user_id`  BIGINT(20) UNSIGNED NOT NULL DEFAULT '0'        COMMENT '归属用户ID，当数据权限归属到用户时',
    `owner_org_id`   BIGINT(20) UNSIGNED NOT NULL DEFAULT '0'        COMMENT '归属门店ID（组织ID），当数据权限归属到本组织以及本下级',
    PRIMARY KEY (`id`),
    KEY `idx_so_id` (`so_id`),
    KEY `idx_interface_type` (`interface_type`),
    KEY `idx_call_time` (`call_time`),
    KEY `idx_result_status` (`result_status`)
) ENGINE = InnoDB DEFAULT CHARSET = utf8mb4 COLLATE = utf8mb4_general_ci COMMENT = 'SO接口同步记录表';
